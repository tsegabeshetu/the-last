const dictionaries = { en, am };
let language = localStorage.getItem(CONFIG.languageKey) === 'am' ? 'am' : 'en';
const listeners = new Set();

export function getLanguage() {
  return language;
}

export function t(key, vars) {
  const dictionary = dictionaries[language] || en;
  let value = dictionary[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function setLanguage(next) {
  language = next === 'am' ? 'am' : 'en';
  localStorage.setItem(CONFIG.languageKey, language);
  document.documentElement.lang = language;
  listeners.forEach((listener) => listener(language));
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function applyStoredLanguage() {
  document.documentElement.lang = language;
}
